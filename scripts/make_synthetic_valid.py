#!/usr/bin/env python3
"""Generate synthetic AncestryDNA-shaped fixtures that require exact bytes.

Produces:
  data/demo/synthetic_valid.txt      — large enough to pass the sufficiency gate
  data/demo/mixed_line_endings.txt   — UTF-8 BOM + mixed CRLF/LF

The data is synthetic. Positions and alleles are deterministically generated
from a fixed seed so fixtures are reproducible. This is NOT a real genome and
must never be used to fabricate downstream inference results.
"""

from __future__ import annotations

import random
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEMO = REPO / "data" / "demo"

HEADER_COMMENTS = [
    "#AncestryDNA raw data download",
    "#This file was generated by AncestryDNA at: 10/08/2026 12:30:57 UTC",
    "#Data was collected using AncestryDNA array version: V2.0",
    "#Data is formatted using AncestryDNA converter version: V1.0",
    "#THIS INFORMATION IS FOR YOUR PERSONAL USE AND IS INTENDED FOR GENEALOGICAL "
    "RESEARCH ONLY. IT IS NOT INTENDED FOR MEDICAL, DIAGNOSTIC, OR HEALTH PURPOSES.",
    "#Columns use human reference build 37.1 coordinates on the forward (+) strand.",
]
COLUMN_HEADER = "rsid\tchromosome\tposition\tallele1\tallele2"

BASES = ["A", "C", "G", "T"]


def gen_rows(n_per_chrom: int, seed: int = 42) -> list[str]:
    rng = random.Random(seed)
    rows: list[str] = []
    rsid = 1_000_000
    for chrom in range(1, 23):
        pos = 100_000
        for _ in range(n_per_chrom):
            pos += rng.randint(500, 5_000)
            a1 = rng.choice(BASES)
            # Mostly homozygous, sometimes heterozygous — shaped like real SNP data.
            a2 = a1 if rng.random() < 0.6 else rng.choice(BASES)
            rows.append(f"rs{rsid}\t{chrom}\t{pos}\t{a1}\t{a2}")
            rsid += 1
    return rows


def write_valid() -> None:
    # ~600 per autosome * 22 = ~13,200 autosomal SNPs, above the 10,000 gate.
    rows = gen_rows(n_per_chrom=600)
    lines = HEADER_COMMENTS + [COLUMN_HEADER] + rows
    out = DEMO / "synthetic_valid.txt"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(rows)} synthetic autosomal SNP rows)")


def write_mixed_line_endings() -> None:
    rows = [
        "rs5000001\t1\t700000\tA\tG",
        "rs5000002\t1\t700100\tC\tC",
        "rs5000003\t2\t700200\tT\tC",
        "rs5000004\t3\t700300\tG\tG",
    ]
    data_lines = HEADER_COMMENTS + [COLUMN_HEADER] + rows
    # Alternate CRLF and LF between lines, and prepend a UTF-8 BOM.
    buf = "\ufeff"
    for i, line in enumerate(data_lines):
        buf += line
        buf += "\r\n" if i % 2 == 0 else "\n"
    out = DEMO / "mixed_line_endings.txt"
    out.write_bytes(buf.encode("utf-8"))
    print(f"wrote {out} (BOM + mixed CRLF/LF)")


if __name__ == "__main__":
    DEMO.mkdir(parents=True, exist_ok=True)
    write_valid()
    write_mixed_line_endings()
