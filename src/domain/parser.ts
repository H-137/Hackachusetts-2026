/**
 * AncestryDNA raw-text parser (browser-side, privacy-first).
 *
 * Implements the input contract in HACKATHON_PROJECT_PLAN.md Section 4 rules 1-10.
 * This parser runs locally in the browser so personal uploads never leave the
 * device for the supported lightweight path (Section 11).
 *
 * Privacy invariants enforced here:
 *  - No allele value is ever placed into an error message, the quality summary,
 *    or any thrown error. Errors reference line numbers and codes only.
 *  - allele1 / allele2 are preserved verbatim on records but are NOT interpreted
 *    as parental copies or as REF/ALT (rule #3).
 *
 * This does NOT perform harmonization, reference validation, phasing, ancestry
 * inference, or scoring. Those belong to later milestones. In particular, a file
 * that contains only the four-row example (or any sub-threshold file) parses
 * successfully but reports sufficient_for_inference = false (rule #9).
 */

import {
  EXPECTED_HEADER,
  INDEL_TOKENS,
  NO_CALL_TOKEN,
  SNP_ALLELES,
  normalizeChromosome,
  normalizeDeclaredBuild,
} from "./ancestrydna";
import type {
  ParseError,
  ParseResult,
  ParsedRecord,
  QualitySummary,
  RecordKind,
  SourceMetadata,
} from "./types";

/**
 * Minimum number of analysis-ready autosomal SNPs for a file to be considered
 * potentially sufficient for downstream inference. This is a conservative
 * Step 1 gate to satisfy rule #9 (the four-row example must be insufficient).
 * The genome-wide thresholds that actually block phasing/ancestry are set with
 * numeric justification in Step 2; this value only guards the parser's
 * sufficient_for_inference flag so that trivially small inputs can never be
 * presented as analyzable.
 */
export const MIN_AUTOSOMAL_SNPS_FOR_INFERENCE = 10_000;

const BOM = "\uFEFF";

interface MutableQuality {
  total_records: number;
  parsed_records: number;
  autosomal_records: number;
  no_call_count: number;
  unsupported_indel_count: number;
  duplicate_exact_count: number;
  duplicate_conflicting_count: number;
  excluded_by_chromosome: Record<string, number>;
  error_count: number;
}

function emptyMetadata(): SourceMetadata {
  return {
    source_format: "AncestryDNA-raw-text",
    array_version: null,
    converter_version: null,
    declared_build: "",
    normalized_build: "unknown",
    strand: "",
    generated_at: null,
    usage_notice: "",
  };
}

/** Parse leading `#` comment lines into source metadata (rule #1). */
function parseMetadata(commentLines: string[]): SourceMetadata {
  const meta = emptyMetadata();
  const noticeParts: string[] = [];

  for (const raw of commentLines) {
    const line = raw.replace(/^#/, "").trim();
    if (line.length === 0) continue;

    const arrayMatch = line.match(/array version:\s*(\S+)/i);
    if (arrayMatch?.[1]) meta.array_version = arrayMatch[1];

    const converterMatch = line.match(/converter version:\s*(\S+)/i);
    if (converterMatch?.[1]) meta.converter_version = converterMatch[1];

    const genAtMatch = line.match(/generated by .*? at:\s*(.+)$/i);
    if (genAtMatch?.[1]) meta.generated_at = genAtMatch[1].trim();

    const buildMatch = line.match(/build\s+([\d.]+)/i);
    if (buildMatch?.[1] && !meta.declared_build) meta.declared_build = buildMatch[1];

    const strandMatch = line.match(/\b(forward|reverse)\s*\(([+-])\)/i);
    if (strandMatch?.[2]) meta.strand = strandMatch[2];

    if (/genealogical|not intended for medical|personal use/i.test(line)) {
      noticeParts.push(line);
    }
  }

  meta.normalized_build = normalizeDeclaredBuild(meta.declared_build);
  meta.usage_notice = noticeParts.join(" ");
  return meta;
}

function splitLines(text: string): string[] {
  // Strip an optional UTF-8 BOM, then support both CRLF and LF (rule #2).
  const withoutBom = text.startsWith(BOM) ? text.slice(BOM.length) : text;
  return withoutBom.split(/\r\n|\n|\r/);
}

function classifyAllelePair(
  allele1: string,
  allele2: string,
): { kind: Exclude<RecordKind, "duplicate_exact" | "duplicate_conflicting" | "non_autosomal">; errorCode?: ParseError["code"] } {
  const a1 = allele1.toUpperCase();
  const a2 = allele2.toUpperCase();

  const isNoCall = a1 === NO_CALL_TOKEN || a2 === NO_CALL_TOKEN;
  if (isNoCall) return { kind: "no_call" };

  const isIndel = INDEL_TOKENS.has(a1) || INDEL_TOKENS.has(a2);
  if (isIndel) return { kind: "indel_unsupported", errorCode: "unsupported_indel" };

  const bothSnp = SNP_ALLELES.has(a1) && SNP_ALLELES.has(a2);
  if (bothSnp) return { kind: "snp" };

  return { kind: "indel_unsupported", errorCode: "unexpected_allele_token" };
}

/**
 * Parse an AncestryDNA raw-text string.
 *
 * @param text Full file contents (UTF-8). The caller is responsible for reading
 *             the file locally; this function performs no I/O.
 */
export function parseAncestryDna(text: string): ParseResult {
  const lines = splitLines(text);

  const q: MutableQuality = {
    total_records: 0,
    parsed_records: 0,
    autosomal_records: 0,
    no_call_count: 0,
    unsupported_indel_count: 0,
    duplicate_exact_count: 0,
    duplicate_conflicting_count: 0,
    excluded_by_chromosome: {},
    error_count: 0,
  };
  const errors: ParseError[] = [];
  const records: ParsedRecord[] = [];

  const commentLines: string[] = [];
  let headerSeen = false;
  let headerValid = false;

  // Dedup bookkeeping. Key is build-independent: chrom:pos:rsid.
  // Value is the normalized genotype (sorted alleles) to detect conflicts.
  const seen = new Map<string, string>();

  for (let i = 0; i < lines.length; i++) {
    const lineNumber = i + 1;
    const rawLine = lines[i] ?? "";

    if (rawLine.startsWith("#")) {
      commentLines.push(rawLine);
      continue;
    }

    // Skip blank trailing/interstitial lines silently if empty; otherwise flag.
    if (rawLine.trim().length === 0) {
      continue;
    }

    const cols = rawLine.split("\t");

    // Header row (rule #2): validate the five column names.
    if (!headerSeen) {
      headerSeen = true;
      headerValid =
        cols.length === EXPECTED_HEADER.length &&
        EXPECTED_HEADER.every((name, idx) => cols[idx]?.trim() === name);
      if (!headerValid) {
        errors.push({
          line_number: lineNumber,
          code: "bad_header",
          message: `Expected header columns ${EXPECTED_HEADER.join(", ")}.`,
        });
        q.error_count++;
      }
      continue;
    }

    q.total_records++;

    if (cols.length !== EXPECTED_HEADER.length) {
      errors.push({
        line_number: lineNumber,
        code: "bad_column_count",
        message: `Expected ${EXPECTED_HEADER.length} tab-delimited columns, found ${cols.length}.`,
      });
      q.error_count++;
      continue;
    }

    const rsid = (cols[0] ?? "").trim();
    const chromRaw = (cols[1] ?? "").trim();
    const posRaw = (cols[2] ?? "").trim();
    const allele1 = (cols[3] ?? "").trim();
    const allele2 = (cols[4] ?? "").trim();

    // Position validation (rule #4): positive integer, 1-based source coords.
    if (!/^\d+$/.test(posRaw)) {
      errors.push({
        line_number: lineNumber,
        code: "non_integer_position",
        message: "Position is not a non-negative integer.",
      });
      q.error_count++;
      continue;
    }
    const position1 = Number.parseInt(posRaw, 10);
    if (position1 < 1) {
      errors.push({
        line_number: lineNumber,
        code: "non_positive_position",
        message: "Position must be a positive integer (1-based).",
      });
      q.error_count++;
      continue;
    }
    const position0 = position1 - 1; // 1-based -> internal 0-based (Section 4).

    const chrom = normalizeChromosome(chromRaw);

    // Non-autosomal records: counted with a human-readable reason (rule #4),
    // excluded from the analysis path for this first implementation.
    if (!chrom.autosomal) {
      q.excluded_by_chromosome[chrom.label] =
        (q.excluded_by_chromosome[chrom.label] ?? 0) + 1;
      records.push({
        rsid,
        chromosome_raw: chromRaw,
        chromosome_norm: chrom.norm,
        position_1based: position1,
        position_0based: position0,
        allele1,
        allele2,
        record_kind: "non_autosomal",
      });
      q.parsed_records++;
      continue;
    }

    // Allele classification (rules #5): SNP / no-call / unsupported indel / unexpected token.
    const { kind, errorCode } = classifyAllelePair(allele1, allele2);

    // Duplicate detection (rule #6) applies to analysis-path records.
    const dedupKey = `${chrom.norm}:${position1}:${rsid}`;
    const genotypeNorm = [allele1.toUpperCase(), allele2.toUpperCase()].sort().join("/");

    let recordKind: RecordKind = kind;

    if (seen.has(dedupKey)) {
      if (seen.get(dedupKey) === genotypeNorm) {
        recordKind = "duplicate_exact";
        q.duplicate_exact_count++;
      } else {
        recordKind = "duplicate_conflicting";
        q.duplicate_conflicting_count++;
      }
    } else {
      seen.set(dedupKey, genotypeNorm);

      if (kind === "no_call") {
        q.no_call_count++;
      } else if (kind === "indel_unsupported") {
        q.unsupported_indel_count++;
        if (errorCode) {
          errors.push({
            line_number: lineNumber,
            code: errorCode,
            message:
              errorCode === "unsupported_indel"
                ? "Indel call (D/I) is not supported in the first autosomal SNP implementation."
                : "Unexpected allele token for a SNP call.",
          });
          q.error_count++;
        }
      } else if (kind === "snp") {
        q.autosomal_records++;
      }
    }

    records.push({
      rsid,
      chromosome_raw: chromRaw,
      chromosome_norm: chrom.norm,
      position_1based: position1,
      position_0based: position0,
      allele1,
      allele2,
      record_kind: recordKind,
    });
    q.parsed_records++;
  }

  if (!headerSeen) {
    errors.push({
      line_number: commentLines.length + 1,
      code: "bad_header",
      message: "No data header row was found.",
    });
    q.error_count++;
  }

  const metadata = parseMetadata(commentLines);

  const quality_summary: QualitySummary = {
    ...q,
    sufficient_for_inference:
      headerValid && q.autosomal_records >= MIN_AUTOSOMAL_SNPS_FOR_INFERENCE,
  };

  return { records, metadata, quality_summary, errors };
}
