"""Authoritative AncestryDNA raw-text parser (Python pipeline side).

Implements the input contract in HACKATHON_PROJECT_PLAN.md Section 4 rules 1-10
and mirrors the browser parser in src/domain/parser.ts. Both must agree on the
normalized schema in schemas/normalized.schema.json.

Privacy invariants (Section 11):
  * No allele value is ever written into an error message, the quality summary,
    a log line, or an exception. Errors carry a line number and a code only.
  * allele1 / allele2 are preserved verbatim but NOT interpreted as parental
    copies or as REF/ALT (rule #3).

This parser performs no harmonization, reference validation, phasing, ancestry
inference, or scoring. A file that contains only the four-row example (or any
sub-threshold file) parses successfully but reports
quality_summary.sufficient_for_inference == False (rule #9).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

EXPECTED_HEADER = ("rsid", "chromosome", "position", "allele1", "allele2")

SNP_ALLELES = frozenset({"A", "C", "G", "T"})
NO_CALL_TOKEN = "0"
INDEL_TOKENS = frozenset({"D", "I"})

AUTOSOMES = frozenset(str(i) for i in range(1, 23))
NON_AUTOSOMAL_LABELS = {"23": "X", "24": "Y", "25": "XY/PAR", "26": "MT"}

# Conservative Step 1 gate so trivially small inputs can never be presented as
# analyzable. Genome-wide blocking thresholds are set in Step 2.
MIN_AUTOSOMAL_SNPS_FOR_INFERENCE = 10_000

_BOM = "\ufeff"


def normalize_declared_build(declared: str) -> str:
    d = declared.strip()
    if d.startswith("37"):
        return "GRCh37"
    if d.startswith("38"):
        return "GRCh38"
    return "unknown"


def normalize_chromosome(raw: str) -> tuple[str, bool, str]:
    r = raw.strip()
    if r in AUTOSOMES:
        return r, True, r
    label = NON_AUTOSOMAL_LABELS.get(r)
    if label is not None:
        return label, False, label
    return r, False, r


@dataclass
class SourceMetadata:
    source_format: str = "AncestryDNA-raw-text"
    array_version: str | None = None
    converter_version: str | None = None
    declared_build: str = ""
    normalized_build: str = "unknown"
    strand: str = ""
    generated_at: str | None = None
    usage_notice: str = ""


@dataclass
class ParsedRecord:
    rsid: str
    chromosome_raw: str
    chromosome_norm: str
    position_1based: int
    position_0based: int
    allele1: str
    allele2: str
    record_kind: str


@dataclass
class ParseError:
    line_number: int
    code: str
    message: str  # Must never contain allele values.


@dataclass
class QualitySummary:
    total_records: int = 0
    parsed_records: int = 0
    autosomal_records: int = 0
    no_call_count: int = 0
    unsupported_indel_count: int = 0
    duplicate_exact_count: int = 0
    duplicate_conflicting_count: int = 0
    excluded_by_chromosome: dict[str, int] = field(default_factory=dict)
    error_count: int = 0
    sufficient_for_inference: bool = False


@dataclass
class ParseResult:
    records: list[ParsedRecord]
    metadata: SourceMetadata
    quality_summary: QualitySummary
    errors: list[ParseError]


def _parse_metadata(comment_lines: list[str]) -> SourceMetadata:
    meta = SourceMetadata()
    notice_parts: list[str] = []
    for raw in comment_lines:
        line = raw.lstrip("#").strip()
        if not line:
            continue
        if (m := re.search(r"array version:\s*(\S+)", line, re.I)):
            meta.array_version = m.group(1)
        if (m := re.search(r"converter version:\s*(\S+)", line, re.I)):
            meta.converter_version = m.group(1)
        if (m := re.search(r"generated by .*? at:\s*(.+)$", line, re.I)):
            meta.generated_at = m.group(1).strip()
        if not meta.declared_build and (m := re.search(r"build\s+([\d.]+)", line, re.I)):
            meta.declared_build = m.group(1)
        if (m := re.search(r"\b(?:forward|reverse)\s*\(([+-])\)", line, re.I)):
            meta.strand = m.group(1)
        if re.search(r"genealogical|not intended for medical|personal use", line, re.I):
            notice_parts.append(line)
    meta.normalized_build = normalize_declared_build(meta.declared_build)
    meta.usage_notice = " ".join(notice_parts)
    return meta


def _split_lines(text: str) -> list[str]:
    if text.startswith(_BOM):
        text = text[len(_BOM):]
    return re.split(r"\r\n|\n|\r", text)


def _classify_allele_pair(allele1: str, allele2: str) -> tuple[str, str | None]:
    a1, a2 = allele1.upper(), allele2.upper()
    if a1 == NO_CALL_TOKEN or a2 == NO_CALL_TOKEN:
        return "no_call", None
    if a1 in INDEL_TOKENS or a2 in INDEL_TOKENS:
        return "indel_unsupported", "unsupported_indel"
    if a1 in SNP_ALLELES and a2 in SNP_ALLELES:
        return "snp", None
    return "indel_unsupported", "unexpected_allele_token"


def parse_ancestrydna(text: str) -> ParseResult:
    """Parse AncestryDNA raw-text content.

    Args:
        text: Full UTF-8 file contents. No file I/O is performed here so the
            caller controls how (and whether) the source is read from disk.
    """
    lines = _split_lines(text)

    q = QualitySummary()
    errors: list[ParseError] = []
    records: list[ParsedRecord] = []
    comment_lines: list[str] = []

    header_seen = False
    header_valid = False
    # Dedup key chrom:pos:rsid -> normalized sorted genotype.
    seen: dict[str, str] = {}

    for i, raw_line in enumerate(lines):
        line_number = i + 1

        if raw_line.startswith("#"):
            comment_lines.append(raw_line)
            continue
        if not raw_line.strip():
            continue

        cols = raw_line.split("\t")

        if not header_seen:
            header_seen = True
            header_valid = len(cols) == len(EXPECTED_HEADER) and all(
                cols[idx].strip() == name for idx, name in enumerate(EXPECTED_HEADER)
            )
            if not header_valid:
                errors.append(ParseError(line_number, "bad_header",
                                          f"Expected header columns {', '.join(EXPECTED_HEADER)}."))
                q.error_count += 1
            continue

        q.total_records += 1

        if len(cols) != len(EXPECTED_HEADER):
            errors.append(ParseError(line_number, "bad_column_count",
                                      f"Expected {len(EXPECTED_HEADER)} tab-delimited columns, found {len(cols)}."))
            q.error_count += 1
            continue

        rsid = cols[0].strip()
        chrom_raw = cols[1].strip()
        pos_raw = cols[2].strip()
        allele1 = cols[3].strip()
        allele2 = cols[4].strip()

        if not re.fullmatch(r"\d+", pos_raw):
            errors.append(ParseError(line_number, "non_integer_position",
                                      "Position is not a non-negative integer."))
            q.error_count += 1
            continue
        position1 = int(pos_raw)
        if position1 < 1:
            errors.append(ParseError(line_number, "non_positive_position",
                                      "Position must be a positive integer (1-based)."))
            q.error_count += 1
            continue
        position0 = position1 - 1  # 1-based -> internal 0-based.

        norm, autosomal, label = normalize_chromosome(chrom_raw)

        if not autosomal:
            q.excluded_by_chromosome[label] = q.excluded_by_chromosome.get(label, 0) + 1
            records.append(ParsedRecord(rsid, chrom_raw, norm, position1, position0,
                                        allele1, allele2, "non_autosomal"))
            q.parsed_records += 1
            continue

        kind, error_code = _classify_allele_pair(allele1, allele2)
        dedup_key = f"{norm}:{position1}:{rsid}"
        genotype_norm = "/".join(sorted([allele1.upper(), allele2.upper()]))

        record_kind = kind
        if dedup_key in seen:
            if seen[dedup_key] == genotype_norm:
                record_kind = "duplicate_exact"
                q.duplicate_exact_count += 1
            else:
                record_kind = "duplicate_conflicting"
                q.duplicate_conflicting_count += 1
        else:
            seen[dedup_key] = genotype_norm
            if kind == "no_call":
                q.no_call_count += 1
            elif kind == "indel_unsupported":
                q.unsupported_indel_count += 1
                if error_code:
                    msg = ("Indel call (D/I) is not supported in the first autosomal "
                           "SNP implementation."
                           if error_code == "unsupported_indel"
                           else "Unexpected allele token for a SNP call.")
                    errors.append(ParseError(line_number, error_code, msg))
                    q.error_count += 1
            elif kind == "snp":
                q.autosomal_records += 1

        records.append(ParsedRecord(rsid, chrom_raw, norm, position1, position0,
                                    allele1, allele2, record_kind))
        q.parsed_records += 1

    if not header_seen:
        errors.append(ParseError(len(comment_lines) + 1, "bad_header",
                                  "No data header row was found."))
        q.error_count += 1

    metadata = _parse_metadata(comment_lines)
    q.sufficient_for_inference = (
        header_valid and q.autosomal_records >= MIN_AUTOSOMAL_SNPS_FOR_INFERENCE
    )

    return ParseResult(records=records, metadata=metadata,
                       quality_summary=q, errors=errors)
